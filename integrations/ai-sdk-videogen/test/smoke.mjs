import assert from 'node:assert/strict';
import {generateText, isStepCount} from 'ai';
import {MockLanguageModelV4} from 'ai/test';
import {VideoGen, createVideogenTools} from '../dist/index.js';
const client=new VideoGen({apiKey:'synthetic-test-key'});
let calls=0;
client.account.getMe=async()=>{calls++;return {accountId:'synthetic-account'};};
const all=createVideogenTools({client,wait:false});
assert.equal(Object.keys(all).length,36);
const tools=createVideogenTools({client,include:['getMe','listFiles']});
assert.deepEqual(Object.keys(tools),['getMe','listFiles']);
const model=new MockLanguageModelV4({doGenerate:{content:[{type:'tool-call',toolCallId:'call-1',toolName:'getMe',input:'{}'}],finishReason:{unified:'tool-calls',raw:undefined},usage:{inputTokens:{total:0,noCache:0,cacheRead:0,cacheWrite:0},outputTokens:{total:0,text:0,reasoning:0}},warnings:[]}});
const result=await generateText({model,tools,stopWhen:isStepCount(1),prompt:'Read the connected account.'});
assert.equal(calls,1);
assert.equal(result.toolResults[0]?.toolName,'getMe');
assert.equal(result.toolResults[0]?.output.accountId,'synthetic-account');
let request;
client.workflows.storyboardToVideo=async input=>{request=input;return {workflowRunId:'synthetic-run'};};
const body={scenes:[{prompt:'A product close-up'},{prompt:'Product in use'}],quality:'HIGH',autoExport:true,remixActions:[{type:'ENABLE_CAPTIONS'},{type:'CONVERT_IMAGES_TO_VIDEOS'}]};
assert.equal(typeof all.storyboardToVideo.execute,'function');
assert.deepEqual(await all.storyboardToVideo.execute(body,{toolCallId:'call-2',messages:[]}),{workflowRunId:'synthetic-run'});
assert.deepEqual(request,body);
client.projects.exportProject=async input=>{request=input;return {exportId:'synthetic-export'};};
await all.exportProject.execute({projectId:'synthetic-project',quality:'HIGH'},{toolCallId:'call-3',messages:[]});
assert.deepEqual(request,{projectId:'synthetic-project',quality:'HIGH'});
console.log('AI SDK 7: 36 tools, allowlist, native model tool call, storyboard forwarding and export arguments pass without API calls.');
